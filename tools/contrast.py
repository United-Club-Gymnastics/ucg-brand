"""Color-pair rules: every brand text/background pair with its WCAG contrast ratio, what
the design guide says about it (DG p42-43), and what is allowed: a pair is allowed at a
size when it meets WCAG AA *and* the guide doesn't reject it at that size.

Run from the repo root to regenerate references/color-pairs.md: python tools/contrast.py
Other tools import allowed() so the site and the table can't disagree."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
brand = json.loads((ROOT / "brand.json").read_text(encoding="utf-8"))
C = {c["id"]: (c["name"], c["hex"]) for g in ("primary", "secondary", "neutral") for c in brand["colors"][g]}
ORDER = ["navy", "dark-blue-green", "blue-green", "light-blue", "purple", "red-orange", "golden-yellow", "white"]

# Transcribed from the Design Guide's approved / non-approved color usage pages
# (DG p42-43, ADG p31-32). Keys are (foreground, background).
#   "small": approved at all sizes      "large": approved for larger sizes only
#   "small-no": not approved at smaller sizes   "no": not approved
GUIDE = {}
for fg in ["golden-yellow", "purple", "red-orange", "blue-green", "light-blue"]:
    GUIDE[(fg, "navy")] = "large"
for fg in ["golden-yellow", "purple", "red-orange", "dark-blue-green", "blue-green"]:
    GUIDE[(fg, "white")] = "large"
for bg in ["golden-yellow", "purple", "red-orange", "blue-green", "light-blue"]:
    GUIDE[("navy", bg)] = "large"
for k in [("golden-yellow", "navy"), ("red-orange", "navy"), ("light-blue", "navy"),
          ("red-orange", "white"), ("dark-blue-green", "white"),
          ("navy", "golden-yellow"), ("navy", "purple"), ("navy", "red-orange"), ("navy", "light-blue")]:
    GUIDE[k] = "small"
for k in [("golden-yellow", "purple"), ("purple", "golden-yellow"), ("red-orange", "golden-yellow"),
          ("blue-green", "golden-yellow"), ("light-blue", "golden-yellow"), ("dark-blue-green", "navy"),
          ("navy", "dark-blue-green"), ("red-orange", "purple"), ("white", "light-blue"),
          ("light-blue", "white"), ("purple", "red-orange"), ("dark-blue-green", "red-orange"),
          ("golden-yellow", "red-orange"), ("blue-green", "red-orange"), ("golden-yellow", "light-blue")]:
    GUIDE[k] = "no"
for k in [("navy", "blue-green"), ("purple", "white"), ("blue-green", "white"), ("golden-yellow", "white")]:
    GUIDE[k] = "small-no"


def lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def ratio(a, b):
    x, y = sorted([lum(a), lum(b)])
    return (y + 0.05) / (x + 0.05)


def allowed(fg, bg):
    """'any' (all text sizes), 'large' (large text, icons, logos) or 'never', for palette ids."""
    r, g = ratio(C[fg][1], C[bg][1]), GUIDE.get((fg, bg))
    if g == "no" or r < 3:
        return "never"
    if r >= 4.5 and g not in ("large", "small-no"):
        return "any"
    return "large"


GUIDE_LABEL = {"large": "approved, large", "small": "approved, all sizes", "no": "not approved",
               "small-no": "not approved at small sizes"}
VERDICT = {"any": "Any text", "large": "Large text, icons, logos only", "never": "Never for text or marks"}


def why(fg, bg):
    """Short reason when the guide, not AA, is what limits a pair."""
    r, g, a = ratio(C[fg][1], C[bg][1]), GUIDE.get((fg, bg)), allowed(fg, bg)
    if a == "large" and r >= 4.5:
        return " (passes AA, but the guide approves it for large sizes only)"
    if a == "never" and r >= 3:
        return " (passes AA for large text, but the guide doesn't approve it)"
    return ""


def main():
    rows = []
    for bg in ORDER:
        for fg in ORDER:
            if fg != bg:
                rows.append((bg, fg, ratio(C[fg][1], C[bg][1]), GUIDE_LABEL.get(GUIDE.get((fg, bg)), "")))
    out = ["# Color pairs", "",
           "Every brand text color on every brand background, with its WCAG contrast ratio and what the",
           "design guide says about it (DG p42–43). **A pair is allowed when it meets WCAG AA and the guide",
           "doesn't reject it at that size.** AA: body text needs 4.5:1; large text (24px+ regular, or",
           "18.66px+ bold, i.e. 18pt / 14pt bold), icons and logos need 3:1. Where the guide approves a pair",
           "that fails AA, AA wins; where the guide rejects a pair that passes AA, the guide wins; where the",
           "guide is silent, AA decides. Generated by `tools/contrast.py`.", ""]
    out += ["## Quick list: safe for body text", ""]
    for bg in ORDER:
        ok = [C[fg][0] for b, fg, r, g in rows if b == bg and allowed(fg, bg) == "any"]
        out.append(f"- **On {C[bg][0]}** (`{C[bg][1]}`): " + (", ".join(ok) if ok else "none (large text and marks only)"))
    out += ["", "## Large text, icons and logos only", ""]
    for bg in ORDER:
        lg = [C[fg][0] for b, fg, r, g in rows if b == bg and allowed(fg, bg) == "large"]
        if lg:
            out.append(f"- **On {C[bg][0]}**: " + ", ".join(lg))
    out += ["", "## Full table", "", "| Background | Text | Ratio | Allowed | Guide |", "|---|---|---|---|---|"]
    for bg, fg, r, g in rows:
        out.append(f"| {C[bg][0]} `{C[bg][1]}` | {C[fg][0]} `{C[fg][1]}` | {r:.2f} | {VERDICT[allowed(fg, bg)]}{why(fg, bg)} | {g} |")
    out.append("")
    (ROOT / "references" / "color-pairs.md").write_bytes("\n".join(out).encode("utf-8"))
    print("wrote references/color-pairs.md,", len(rows), "pairs")


if __name__ == "__main__":
    main()
