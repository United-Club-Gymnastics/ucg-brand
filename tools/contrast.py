"""Generate references/color-pairs.md: every brand text/background pair with its
WCAG contrast ratio, what the design guide said about it, and what is allowed now
(AA everywhere). Run from the repo root: python tools/contrast.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
brand = json.loads((ROOT / "brand.json").read_text(encoding="utf-8"))
C = {c["id"]: (c["name"], c["hex"]) for g in ("primary", "secondary", "neutral") for c in brand["colors"][g]}
ORDER = ["navy", "dark-blue-green", "blue-green", "light-blue", "purple", "red-orange", "golden-yellow", "white"]

# Transcribed from the Design Guide's approved / non-approved color usage pages
# (DG p42-43, ADG p31-32). Keys are (foreground, background).
GUIDE = {}
for fg in ["golden-yellow", "purple", "red-orange", "blue-green", "light-blue"]:
    GUIDE[(fg, "navy")] = "large"
for fg in ["golden-yellow", "purple", "red-orange", "dark-blue-green", "blue-green"]:
    GUIDE[(fg, "white")] = "large"
for bg in ["golden-yellow", "purple", "red-orange", "blue-green", "light-blue"]:
    GUIDE[("navy", bg)] = "large"
for k in [("golden-yellow", "navy"), ("red-orange", "navy"), ("light-blue", "navy"),
          ("red-orange", "white"), ("dark-blue-green", "white"),
          ("navy", "golden-yellow"), ("navy", "purple"), ("navy", "red-orange"), ("navy", "light-blue")]:
    GUIDE[k] = "small"
for k in [("golden-yellow", "purple"), ("purple", "golden-yellow"), ("red-orange", "golden-yellow"),
          ("blue-green", "golden-yellow"), ("light-blue", "golden-yellow"), ("dark-blue-green", "navy"),
          ("navy", "dark-blue-green"), ("red-orange", "purple"), ("white", "light-blue"),
          ("light-blue", "white"), ("purple", "red-orange"), ("dark-blue-green", "red-orange"),
          ("golden-yellow", "red-orange"), ("blue-green", "red-orange"), ("golden-yellow", "light-blue")]:
    GUIDE[k] = "no"
GUIDE_SMALL_NO = {("navy", "blue-green"), ("purple", "white"), ("blue-green", "white"), ("golden-yellow", "white")}


def lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def ratio(a, b):
    x, y = sorted([lum(a), lum(b)])
    return (y + 0.05) / (x + 0.05)


def verdict(r):
    if r >= 4.5:
        return "Any text"
    if r >= 3:
        return "Large text, icons, logos only"
    return "Never for text or marks"


guide_label = {"large": "approved, large", "small": "approved, all sizes", "no": "not approved"}
rows = []
for bg in ORDER:
    for fg in ORDER:
        if fg == bg:
            continue
        r = ratio(C[fg][1], C[bg][1])
        g = guide_label.get(GUIDE.get((fg, bg)), "")
        if (fg, bg) in GUIDE_SMALL_NO:
            g = "not approved at small sizes"
        rows.append((bg, fg, r, g))

out = ["# Color pairs", "",
       "Every brand text color on every brand background, with its WCAG contrast ratio.",
       "**UCG rule: AA everywhere.** Body text needs 4.5:1. Large text (24px+ regular, 18.5px+ bold),",
       "icons and logos need 3:1. The 'Guide' column is what the 2026 design guide said; where the",
       "guide approved a pair that fails AA, the AA rule wins. Generated by `tools/contrast.py`.", ""]
out += ["## Quick list: safe for body text", ""]
for bg in ORDER:
    ok = [C[fg][0] for b, fg, r, g in rows if b == bg and r >= 4.5 and g != "not approved"]
    out.append(f"- **On {C[bg][0]}** (`{C[bg][1]}`): " + (", ".join(ok) if ok else "none"))
out += ["", "## Full table", "", "| Background | Text | Ratio | Allowed now | Guide |", "|---|---|---|---|---|"]
for bg, fg, r, g in rows:
    allowed = verdict(r)
    if g == "not approved" and r >= 3:
        allowed += " (guide says avoid; prefer another pair)"
    out.append(f"| {C[bg][0]} `{C[bg][1]}` | {C[fg][0]} `{C[fg][1]}` | {r:.2f} | {allowed} | {g} |")
out.append("")
(ROOT / "references" / "color-pairs.md").write_text("\n".join(out), encoding="utf-8")
print("wrote references/color-pairs.md,", len(rows), "pairs")
